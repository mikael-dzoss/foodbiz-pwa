export function buildSeedSql(fixtures: SeedFixtures = DEFAULT_FIXTURES): string {
  const anchorDate = findAnchorDate(fixtures.orders);
  const shiftAssignment =
    anchorDate === null
      ? "  v_days := 0;"
      : // "Today" in the shop's time zone, not the session's (UTC on hosted Supabase).
        `  v_days := greatest(0, (now() at time zone ${sqlText(fixtures.settings.timezone)})::date - date ${sqlText(anchorDate)});`;

  const statements = [
    renderDemoDeletes(fixtures.business.id),
    renderBusinessInsert(fixtures.business),
    renderBusinessSettingsInsert(fixtures.settings),
    renderCategoriesInsert(fixtures.categories),
    renderProductsInsert(fixtures.products),
    renderGuestsInsert(fixtures.guests),
    renderOrdersInsert(fixtures.orders),
    renderOrderItemsInsert(fixtures.orders),
    renderExpensesInsert(fixtures.expenses),
  ].filter((stmt): stmt is string => stmt !== null);

  return [
    HEADER_COMMENT,
    "",
    "do $seed$",
    "declare",
    "  v_days integer;",
    "begin",
    shiftAssignment,
    "",
    statements.join("\n\n"),
    "end",
    "$seed$;",
    "",
  ].join("\n");
}
