export function sqlText(value: string): string {
  // The whole seed runs inside a `do $seed$ ... $seed$` block; this tag would end it early.
  if (value.includes("$seed$")) {
    throw new Error("Seed fixture text must not contain the $seed$ dollar-quote tag");
  }
  return `'${value.replace(/'/g, "''")}'`;
}

export function sqlNullableText(value: string | null | undefined): string {
  return value == null ? "null" : sqlText(value);
}

export function sqlUuid(value: string): string {
  return `${sqlText(value)}::uuid`;
}

export function sqlNumber(value: number): string {
  if (!Number.isFinite(value)) {
    throw new Error(`Expected a finite number for SQL literal, got ${String(value)}`);
  }
  return String(value);
}

export function sqlNullableNumber(value: number | null | undefined): string {
  return value == null ? "null" : sqlNumber(value);
}

export function sqlBoolean(value: boolean): string {
  return value ? "true" : "false";
}

export function sqlTextArray(values: readonly string[]): string {
  if (values.length === 0) {
    return "array[]::text[]";
  }
  return `array[${values.map(sqlText).join(", ")}]::text[]`;
}

export function sqlJsonb(value: unknown): string {
  return `${sqlText(JSON.stringify(value))}::jsonb`;
}

export function sqlNullableJsonb(value: unknown): string {
  return value == null ? "null" : sqlJsonb(value);
}

function sqlShiftedHoursExceptions(exceptions: readonly HoursException[] | undefined): string {
  if (!exceptions || exceptions.length === 0) {
    return "'[]'::jsonb";
  }
  const entries = exceptions.map((ex) => {
    const fields = [
      `'from', to_char(${sqlShiftedDate(ex.from)}, 'YYYY-MM-DD')`,
      `'to', to_char(${sqlShiftedDate(ex.to)}, 'YYYY-MM-DD')`,
      `'ranges', ${sqlJsonb(ex.ranges)}`,
      ...(ex.note !== undefined ? [`'note', ${sqlText(ex.note)}`] : []),
    ];
    return `      jsonb_build_object(${fields.join(", ")})`;
  });
  return `jsonb_build_array(\n${entries.join(",\n")}\n    )`;
}

function sqlTimestamp(iso: string): string {
  return `${sqlText(iso)}::timestamptz`;
}

function sqlShiftedTimestamp(iso: string): string {
  return `${sqlText(iso)}::timestamptz + make_interval(days => v_days)`;
}

function sqlNullableShiftedTimestamp(iso: string | null | undefined): string {
  return iso == null ? "null" : sqlShiftedTimestamp(iso);
}

function sqlShiftedDate(dateStr: string): string {
  return `date ${sqlText(dateStr.slice(0, 10))} + v_days`;
}

function sqlNullableTime(timeStr: string | null | undefined): string {
  return timeStr == null ? "null" : `${sqlText(timeStr)}::time`;
}

function sqlStatusHistory(events: readonly OrderStatusEvent[] | undefined): string {
  if (!events || events.length === 0) {
    // An empty history would be filled by the 0024 trigger with the unshifted run time.
    throw new Error("Seed orders must have a non-empty statusHistory");
  }

  const entries = events.map((event) => {
    const shiftedIso = `to_char((${sqlText(event.timestamp)}::timestamptz + make_interval(days => v_days)) at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')`;
    return `        jsonb_build_object('status', ${sqlText(event.status)}, 'timestamp', ${shiftedIso}, 'note', ${sqlNullableText(event.note)})`;
  });

  return `jsonb_build_array(\n${entries.join(",\n")}\n      )`;
}

function findAnchorDate(orders: readonly Order[]): string | null {
  let newest: string | null = null;
  for (const order of orders) {
    const candidates = [order.requestedDate.slice(0, 10), order.createdAt.slice(0, 10)];
    for (const candidate of candidates) {
      if (newest === null || candidate > newest) {
        newest = candidate;
      }
    }
  }
  return newest;
}

function buildUpdateSetClause(
  columns: readonly string[],
  exclude: readonly string[] = ["id"],
): string {
  const excluded = new Set(exclude);
  return columns
    .filter((col) => !excluded.has(col))
    .map((col) => `    ${col} = excluded.${col}`)
    .join(",\n");
}

